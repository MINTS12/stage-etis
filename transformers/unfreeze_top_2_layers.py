MODEL_NAME    = "seyonec/ChemBERTa-zinc-base-v1"
GPU_ID        = "cuda:0"
MAX_LEN       = 128
BATCH_SIZE    = 32                 # smaller than frozen runs — backbone now runs every batch
MAX_EPOCHS    = 100
PATIENCE      = 10                  # early stopping patience (epochs without val macro-F1 improvement)

# Two-LR setup
LR_HEAD       = 1e-4
LR_BACKBONE   = 1e-5               # safe start; can range 5e-6 to 2e-5
WEIGHT_DECAY  = 0.01
WARMUP_FRAC   = 0.10               # warmup over first 10% of total steps

# Unfreezing
N_UNFROZEN_LAYERS = 2              # top-2 transformer layers unfrozen

# SMILES enumeration
N_SMILES_VARIANTS = 20             # variants generated per molecule, resampled each epoch

# ASL hyperparameters
ASL_GAMMA_POS   = 0
ASL_GAMMA_NEG   = 4                # start at 2; raise to 3-4 if rare labels still lag
ASL_MARGIN      = 0.05
LABEL_SMOOTHING = 0.05

