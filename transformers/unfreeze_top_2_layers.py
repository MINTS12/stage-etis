"""
Experiment: Phase 1 Fine-tuning — ChemBERTa (top 2 layers unfrozen) + MLP head + ASL
Goal : classify the 12 metacategories and beat the BR+RF baseline (macro PR AUC 0.624)

Strategy:
  - Embeddings + layers 1-4 frozen
  - Layers 5-6 (top 2 transformer layers) unfrozen
  - MLP head trainable
  - Two learning rates: backbone (low) vs head (higher)
  - Linear warmup (10% of steps) -> cosine decay
  - On-the-fly SMILES enumeration (20-30 variants per molecule, re-sampled every epoch)
  - ASL with gamma_neg=2 (tune up to 3-4 if rare labels still lag) + label smoothing
  - Early stopping on validation macro-F1 (patience 5-10), not loss
  - Post-hoc per-label threshold calibration on validation set
"""

